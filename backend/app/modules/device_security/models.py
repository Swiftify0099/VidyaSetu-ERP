class LoginVerificationRequest(Base):
    """
    Pending device verification.
    Created when a login is attempted from an unrecognized device.
    
    Security rules:
    - Token is single-use
    - Token expires after DEVICE_VERIFICATION_TOKEN_EXPIRE_MINUTES
    - Maximum 5 attempts before lockout
    - Token hash stored (never plaintext)
    """
    __tablename__ = "login_verification_requests"

    # UUID string PK — opaque, non-guessable
    id: Mapped[str] = mapped_column(String(36), primary_key=True)

    # ── References ────────────────────────────────────────────
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False, index=True
    )
    device_id: Mapped[Optional[int]] = mapped_column(
        BigInteger, ForeignKey("user_devices.id", ondelete="SET NULL"),
        nullable=True
    )
    login_attempt_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True, index=True)

    # ── Verification Token (HASHED — never store plaintext) ───
    verification_token_hash: Mapped[str] = mapped_column(String(255), nullable=False, index=True)

    # ── Status ────────────────────────────────────────────────
    status: Mapped[str] = mapped_column(
        String(20), nullable=False, default=VerificationStatus.PENDING
    )

    # ── Rate Limiting ─────────────────────────────────────────
    attempts: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    max_attempts: Mapped[int] = mapped_column(Integer, default=5, nullable=False)

    # ── Timing ────────────────────────────────────────────────
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    verified_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    rejected_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # ── Request Context ───────────────────────────────────────
    ip_address: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    user_agent: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # ── Timestamps ────────────────────────────────────────────
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utc_now, nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False
    )

    @property
    def is_expired(self) -> bool:
        return datetime.now(self.expires_at.tzinfo) > self.expires_at

    @property
    def is_exhausted(self) -> bool:
        return self.attempts >= self.max_attempts

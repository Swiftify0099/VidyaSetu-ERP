# ═══════════════════════════════════════════════════════════════
# UserDevice
# ═══════════════════════════════════════════════════════════════

class UserDevice(BaseModel):
    """
    Registered device for a user.
    1 Primary + Maximum 2 Temporary devices per user.
    Exactly ONE primary per user (enforced in service and DB).
    
    Device identity is based on a cryptographically random installation ID
    generated by the client (browser or mobile app).
    We NEVER collect IMEI, MAC address, or other restricted hardware identifiers.
    """
    __tablename__ = "user_devices"

    # ── Ownership ─────────────────────────────────────────────
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False, index=True
    )

    # ── Device Identity ───────────────────────────────────────
    # High-entropy UUID generated on the client. Never a hardware identifier.
    device_installation_id: Mapped[str] = mapped_column(
        String(255), nullable=False, index=True
    )

    # ── Device Metadata ───────────────────────────────────────
    device_type: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)      # web | android | ios
    platform: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    manufacturer: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    model: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    os_version: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    app_version: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    browser_name: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    browser_version: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    user_agent: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    timezone: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    language: Mapped[Optional[str]] = mapped_column(String(20), nullable=True)

    # ── Trust & Role State ─────────────────────────────────────
    is_primary: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    is_trusted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    is_temporary: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    status: Mapped[str] = mapped_column(String(20), default=DeviceStatus.PENDING, nullable=False)
    revoke_reason: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # ── Timing & Expiration ───────────────────────────────────
    first_seen_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    last_seen_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    trusted_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    temporary_started_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    temporary_expires_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True, index=True)
    revoked_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # ── Relationships ─────────────────────────────────────────
    user: Mapped["app.modules.auth.models.User"] = relationship(  # type: ignore[name-defined]
        "User", foreign_keys=[user_id], lazy="select"
    )
    login_events: Mapped[list["LoginEvent"]] = relationship(
        "LoginEvent", back_populates="device", lazy="select"
    )

    @property
    def display_name(self) -> str:
        """Human-readable device name for UI display."""
        if self.device_type == "web":
            parts = []
            if self.browser_name:
                parts.append(self.browser_name)
            if self.os_version:
                parts.append(self.os_version)
            return " on ".join(parts) if parts else "Web Browser"
        elif self.device_type in ("android", "ios"):
            parts = []
            if self.manufacturer:
                parts.append(self.manufacturer)
            if self.model:
                parts.append(self.model)
            return " ".join(parts) if parts else (self.device_type or "Mobile Device").title()
        return "Unknown Device"



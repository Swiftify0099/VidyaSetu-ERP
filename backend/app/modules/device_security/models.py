class LoginEvent(BaseModel):
    """
    Immutable login audit event.
    Every significant security event is recorded here.
    Normal users cannot modify or delete these records.
    """
    __tablename__ = "login_events"

    # ── References ────────────────────────────────────────────
    user_id: Mapped[Optional[int]] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True, index=True
    )
    device_id: Mapped[Optional[int]] = mapped_column(
        BigInteger, ForeignKey("user_devices.id", ondelete="SET NULL"),
        nullable=True
    )
    # Groups all events belonging to one login attempt
    login_attempt_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True, index=True)

    # ── Event Classification ──────────────────────────────────
    event_type: Mapped[str] = mapped_column(String(60), nullable=False, index=True)
    status: Mapped[Optional[str]] = mapped_column(String(20), nullable=True)

    # ── Request Context ───────────────────────────────────────
    ip_address: Mapped[Optional[str]] = mapped_column(String(50), nullable=True, index=True)
    user_agent: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    device_type: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    platform: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    browser: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    os: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # ── Location (only when explicitly provided by client) ────
    approximate_location: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    latitude: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    longitude: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    location_accuracy: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # ── Event Metadata ────────────────────────────────────────
    login_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    verification_required: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    verification_method: Mapped[Optional[str]] = mapped_column(String(20), nullable=True)
    risk_score: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    failure_reason: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # ── Relationships ─────────────────────────────────────────
    device: Mapped[Optional[UserDevice]] = relationship(
        "UserDevice", back_populates="login_events", lazy="select"
    )


